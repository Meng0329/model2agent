"""Uniform Model Agent builder.

Takes an AssetDescriptor + MCG and emits a *standalone* Model Agent under
generated_agents/<slug>/. The same template generates every agent — there is NO
per-model hand-written agent code (a hard research constraint). The generated
agent imports the asset's native `infer` module (real weights) and routes
natural-language queries to the induced capabilities via the DeepSeek LLM.
"""
from __future__ import annotations
import json
import textwrap
from pathlib import Path

from .. import config
from ..agci.asset_scanner import AssetDescriptor
from ..mcg.graph import ModelCapabilityGraph

AGENT_TEMPLATE = '''#!/usr/bin/env python3
"""Standalone Model Agent for {slug} — AUTO-GENERATED by Model2Agent (uniform template).

Independently launchable; calls real weights via the asset's native infer module;
uses the external DeepSeek API for natural-language routing. Do not hand-edit per model.
"""
import os, sys, json, time, importlib.util
os.environ.setdefault("CUDA_VISIBLE_DEVICES", "0")
BUNDLE_DIR = {bundle_dir!r}
# Standalone launch: locate and load the project .env by walking up from BUNDLE_DIR.
try:
    from dotenv import load_dotenv as _load_dotenv
    _d = BUNDLE_DIR
    for _ in range(4):
        if os.path.exists(os.path.join(_d, ".env")):
            _load_dotenv(os.path.join(_d, ".env"))
            break
        _d = os.path.dirname(_d)
except Exception:
    pass
# Load the asset's native infer module under a UNIQUE name to avoid the global
# `import infer` collision when multiple Model Agents live in one process.
_spec = importlib.util.spec_from_file_location("m2a_infer_" + {slug!r}, os.path.join(BUNDLE_DIR, "infer.py"))
_infer = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = _infer
_spec.loader.exec_module(_infer)
from openai import OpenAI

_CAPS = {caps_json}
_MCG = {mcg_json}
_CLIENT = OpenAI(base_url=os.getenv("DEEPSEEK_BASE_URL"), api_key=os.getenv("DEEPSEEK_API_KEY"))
_MODEL = os.getenv("DEEPSEEK_MODEL", "deepseek-v4.1-flash")

def list_capabilities():
    return [c["name"] for c in _CAPS]

def _extract_json(t):
    import re as _re
    if not t: return None
    tt = t.strip()
    try: return json.loads(tt)
    except Exception: pass
    m = _re.search(r'```(?:json)?\\s*(\\{{.*\\}})\\s*```', tt, _re.S)
    if m:
        try: return json.loads(m.group(1))
        except Exception: pass
    i, j = tt.find('{{'), tt.rfind('}}')
    if i != -1 and j != -1 and j > i:
        try: return json.loads(tt[i:j+1])
        except Exception: pass
    return None

def _fn(name):
    for c in _CAPS:
        if c["name"] == name:
            return c["entry_function"]
    raise KeyError(name)

def run_capability(name, args=None):
    """Execute a capability directly against the real model (deterministic wrapper)."""
    args = args or {{}}
    fn = getattr(_infer, _fn(name))
    return fn(**args)

def query(natural_language: str, temperature: float = 0.0) -> dict:
    """Route a natural-language query to a capability, execute it on real weights,
    and return the result plus an LLM-formed natural-language answer."""
    spec = json.dumps(_CAPS, ensure_ascii=False)
    msg = [
        {{"role":"system","content":"You route user requests to exactly one model capability. "
         "Given the capability list (with input_schema), choose the capability and produce "
         "JSON args matching its schema. Output ONLY one JSON object with NO preamble: "
         "{{\\"capability\\":..,\\"args\\":{{}}}}."}},
        {{"role":"user","content":"Capabilities:\\n" + spec + "\\n\\nRequest: " + natural_language}},
    ]
    t0 = time.perf_counter()
    _tok = 0
    plan = None
    raw = ""
    for _attempt in range(2):
        routing = _CLIENT.chat.completions.create(model=_MODEL, messages=msg, temperature=temperature,
                                                  max_tokens=2500, reasoning_effort="none",
                                                  response_format={{"type":"json_object"}})
        raw = routing.choices[0].message.content
        _tok += (getattr(routing, "usage", None) and getattr(routing.usage, "total_tokens", 0)) or 0
        plan = _extract_json(raw)
        if isinstance(plan, dict):
            break
        # retry with a terse, stricter instruction
        msg = [
            {{"role":"system","content":"Return ONLY a JSON object {{\\"capability\\": <name>, \\"args\\": {{<schema args>}}}} and nothing else."}},
            {{"role":"user","content":"Capabilities: " + spec + "\\nRequest: " + natural_language}},
        ]
    if not isinstance(plan, dict):
        return {{"ok": False, "error": "routing_parse", "raw": (raw or "")[:300], "tokens": _tok}}
    cap, args = plan.get("capability"), plan.get("args", {{}})
    try:
        result = run_capability(cap, args)
    except Exception as e:
        return {{"ok": False, "capability": cap, "args": args, "error": f"{{type(e).__name__}}: {{e}}", "tokens": _tok}}
    # Form a natural-language answer grounded in the executed result.
    ans = _CLIENT.chat.completions.create(model=_MODEL, messages=[
        {{"role":"system","content":"Answer the user's request using ONLY the executed model result. Be concise."}},
        {{"role":"user","content":f"Request: {{natural_language}}\\nCapability: {{cap}}\\nExecuted result (JSON): {{json.dumps(result, ensure_ascii=False)[:2000]}}"}},
    ], temperature=temperature, max_tokens=700, reasoning_effort="none")
    _tok += (getattr(ans, "usage", None) and getattr(ans.usage, "total_tokens", 0)) or 0
    return {{"ok": True, "capability": cap, "args": args, "result": result,
             "nl_answer": ans.choices[0].message.content,
             "tokens": _tok, "latency_ms": (time.perf_counter()-t0)*1000}}

if __name__ == "__main__":
    import argparse
    p = argparse.ArgumentParser()
    p.add_argument("mode", choices=["caps","run","query"])
    p.add_argument("--name"); p.add_argument("--args", default="{{}}"); p.add_argument("--q", default="")
    a = p.parse_args()
    if a.mode == "caps":
        print(json.dumps(list_capabilities(), ensure_ascii=False))
    elif a.mode == "run":
        print(json.dumps(run_capability(a.name, json.loads(a.args)), ensure_ascii=False))
    elif a.mode == "query":
        print(json.dumps(query(a.q), ensure_ascii=False, default=str))
'''

CLI_TEMPLATE = '''#!/usr/bin/env python3
"""CLI launcher for the {slug} Model Agent."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import agent
if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "serve":
        import gradio as gr
        def q(x):
            import json; return json.dumps(agent.query(x), ensure_ascii=False, default=str)
        gr.Interface(fn=q, inputs="text", outputs="text", title="Model Agent: {slug}").launch()
    else:
        print(agent.query(" ".join(sys.argv[1:])))
'''


def build_agent(descriptor: AssetDescriptor, mcg: ModelCapabilityGraph, out_dir=None) -> Path:
    out = Path(out_dir) if out_dir else config.GENERATED_AGENTS_DIR / descriptor.slug
    out.mkdir(parents=True, exist_ok=True)
    caps_json = json.dumps([c if isinstance(c, dict) else c.__dict__ for c in (mcg.nodes if hasattr(mcg, "nodes") else [])],
                           ensure_ascii=False, indent=2)
    # mcg.nodes may be dicts already
    caps = mcg.to_dict()["nodes"]
    caps_json = json.dumps(caps, ensure_ascii=False)
    mcg_json = json.dumps(mcg.to_dict(), ensure_ascii=False)
    agent_src = AGENT_TEMPLATE.format(slug=descriptor.slug, bundle_dir=descriptor.bundle_dir,
                                      caps_json=caps_json, mcg_json=mcg_json)
    (out / "agent.py").write_text(agent_src, encoding="utf-8")
    (out / "run.py").write_text(CLI_TEMPLATE.format(slug=descriptor.slug), encoding="utf-8")
    (out / "manifest.json").write_text(json.dumps({
        "slug": descriptor.slug, "model_id": descriptor.model_id,
        "task_family": descriptor.task_family, "bundle_dir": descriptor.bundle_dir,
        "caps": caps, "mcg": mcg.to_dict(),
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    return out
